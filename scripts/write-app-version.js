const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const versionConfigPath = path.join(repoRoot, 'app-version.json');
const changelogSourcePath = path.join(repoRoot, 'changelog.json');
const allTargetApps = ['admin', 'agents'];

const getTargetApps = () => {
  const cwd = path.resolve(process.cwd());

  if (cwd === path.join(repoRoot, 'admin')) return ['admin'];
  if (cwd === path.join(repoRoot, 'agents')) return ['agents'];

  return allTargetApps;
};

const configFileFor = (app, fileName) => path.join(repoRoot, app, 'src', 'config', fileName);

const readGit = (args, fallback) => {
  try {
    const value = execFileSync('git', args, {
      cwd: repoRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();

    return value || fallback;
  } catch (error) {
    return fallback;
  }
};

const hasPendingChanges = () => readGit(['status', '--porcelain'], '') !== '';

const readMajorVersion = () => {
  const config = JSON.parse(fs.readFileSync(versionConfigPath, 'utf8'));
  const major = Number(process.env.APP_MAJOR_VERSION || config.major || 1);

  if (!Number.isInteger(major) || major < 1) {
    throw new Error('app-version.json must define "major" as an integer greater than 0.');
  }

  return major;
};

const wait = (milliseconds) => {
  const end = Date.now() + milliseconds;

  while (Date.now() < end) {
    // Wait for Windows file locks during parallel builds.
  }
};

const writeFileIfChanged = (targetFile, content) => {
  if (fs.existsSync(targetFile) && fs.readFileSync(targetFile, 'utf8') === content) {
    return false;
  }

  let lastError;

  for (let attempt = 0; attempt < 5; attempt += 1) {
    try {
      fs.writeFileSync(targetFile, content);
      return true;
    } catch (error) {
      lastError = error;

      if (!['EPERM', 'EBUSY'].includes(error.code)) {
        throw error;
      }

      wait(100 * (attempt + 1));
    }
  }

  throw lastError;
};

const readChangelogEntries = () => {
  try {
    const parsed = JSON.parse(fs.readFileSync(changelogSourcePath, 'utf8'));
    return Array.isArray(parsed.entries) ? parsed.entries : [];
  } catch (error) {
    return [];
  }
};

// Cada app recibe solo lo que le incumbe.
const audienceForApp = { admin: 'admin', agents: 'agente' };

/**
 * Filtra las novedades por audiencia.
 *
 * La audiencia se declara por ítem ("audiencia": "admin" | "agente" | "todos")
 * y puede fijarse para toda la entrada. Sin declarar, es "todos": las entradas
 * viejas se siguen viendo igual en las dos apps.
 *
 * Una entrada que se queda sin ítems para esa app no se publica.
 */
const filterByAudience = (entries, audience) => entries
  .map((entry) => ({
    ...entry,
    items: (entry.items || []).filter((item) => {
      const target = String(item.audiencia || entry.audiencia || 'todos').toLowerCase();
      return target === 'todos' || target === audience;
    }),
  }))
  .filter((entry) => entry.items.length > 0);

const major = readMajorVersion();
const headCommitCount = Number(readGit(['rev-list', '--count', 'HEAD'], '0'));
const commitCount = headCommitCount + (hasPendingChanges() ? 1 : 0);
const appVersion = `v${major}.${commitCount}`;
const buildDate = new Date().toISOString();

const versionFileContent = `// Auto-generated by scripts/write-app-version.js. Do not edit by hand.
export const APP_VERSION = '${appVersion}';
export const APP_VERSION_MAJOR = ${major};
export const APP_COMMIT_COUNT = ${commitCount};
export const APP_BUILD_DATE = '${buildDate}';

export default APP_VERSION;
`;

const allEntries = readChangelogEntries();

const changelogFileContentFor = (app) => {
  const entries = filterByAudience(allEntries, audienceForApp[app] || 'todos');

  return `// Auto-generated by scripts/write-app-version.js from changelog.json (repo root).
// Do not edit by hand: edit changelog.json instead.
// Filtrado para "${app}": solo las novedades que le incumben a esta app.
export const CHANGELOG_ENTRIES = ${JSON.stringify(entries, null, 2)};

export default CHANGELOG_ENTRIES;
`;
};

getTargetApps().forEach((app) => {
  const versionFile = configFileFor(app, 'appVersion.js');
  const changelogFile = configFileFor(app, 'changelog.js');

  fs.mkdirSync(path.dirname(versionFile), { recursive: true });
  writeFileIfChanged(versionFile, versionFileContent);
  writeFileIfChanged(changelogFile, changelogFileContentFor(app));
});

console.log(`App version generated: ${appVersion}`);
